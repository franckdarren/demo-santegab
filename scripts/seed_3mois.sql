    service_id_v := '22222222-' || lpad(rec.sidx::TEXT, 4, '0') || '-0000-0000-' || lpad(rec.sidx::TEXT, 12, '0');

    SELECT id INTO chambre_id_v FROM chambres WHERE hospital_id = hosp_id AND numero = rec.ch_num;

    -- Premier lit de la chambre (trié par nom)
    SELECT id INTO lit_id_v
    FROM lits
    WHERE chambre_id = chambre_id_v AND hospital_id = hosp_id
    ORDER BY nom ASC
    LIMIT 1;

    date_v := debut + (rec.day_entree || ' days')::INTERVAL + INTERVAL '8 hours';
    IF rec.duree IS NOT NULL THEN
      duree := rec.duree;
      date_sortie := debut + ((rec.day_entree + rec.duree) || ' days')::INTERVAL + INTERVAL '11 hours';
    ELSE
      date_sortie := NULL;
      duree := GREATEST(1, FLOOR(EXTRACT(EPOCH FROM ('2026-04-26 12:00:00+00'::TIMESTAMPTZ - date_v)) / 86400)::INT);
    END IF;

    -- Calcul montants
    SELECT prix_journalier INTO prix_chambre FROM chambres WHERE id = chambre_id_v;
    prix_total := prix_chambre * duree;

    -- + médicaments
    SELECT prix_total + COALESCE(SUM(a.prix_unitaire * hm.qte), 0) INTO prix_total
    FROM _hmed hm
    JOIN articles_stock a ON a.code_article = hm.code AND a.hospital_id = hosp_id
    WHERE hm.ord = rec.ord;

    -- + actes
    SELECT prix_total + COALESCE(SUM(prix * qte), 0) INTO prix_total
    FROM _hacte WHERE ord = rec.ord;

    SELECT pt.taux INTO taux FROM _patient_taux pt WHERE pt.idx = rec.pidx;
    m_assurance := ROUND(prix_total * (taux / 100.0));
    m_patient := prix_total - m_assurance;

    -- Facture
    INSERT INTO factures (id, hospital_id, patient_id, numero_facture, statut, montant_total, montant_assurance, montant_patient, mode_paiement, date_paiement, notes, created_at, updated_at)
    VALUES (fact_id, hosp_id, patient_id_v, num_facture,
            rec.fact_st::"StatutFacture", prix_total, m_assurance, m_patient,
            CASE WHEN rec.paiement IS NOT NULL THEN rec.paiement::"ModePaiement" ELSE NULL END,
            CASE WHEN rec.fact_st = 'PAYEE' THEN date_sortie ELSE NULL END,
            'Hospitalisation — ' || rec.motif, date_v, date_v);

    -- Lignes facture : chambre
    INSERT INTO ligne_factures (facture_id, description, quantite, prix_unitaire, montant_total, created_at)
    VALUES (fact_id, 'Chambre ' || rec.ch_num || ' x' || duree || ' jour(s)', duree, prix_chambre, prix_chambre * duree, date_v);

    -- Lignes facture : médicaments
    INSERT INTO ligne_factures (facture_id, description, quantite, prix_unitaire, montant_total, created_at)
    SELECT fact_id,
           a.nom || ' x' || hm.qte || ' ' || a.unite,
           hm.qte, a.prix_unitaire, a.prix_unitaire * hm.qte, date_v
    FROM _hmed hm
    JOIN articles_stock a ON a.code_article = hm.code AND a.hospital_id = hosp_id
    WHERE hm.ord = rec.ord;

    -- Lignes facture : actes
    INSERT INTO ligne_factures (facture_id, description, quantite, prix_unitaire, montant_total, created_at)
    SELECT fact_id, description, qte, prix, prix * qte, date_v
    FROM _hacte WHERE ord = rec.ord;

    -- Hospitalisation
    INSERT INTO hospitalisations (id, hospital_id, patient_id, medecin_id, chambre_id, lit_id, service_id, statut, date_entree, date_sortie, motif_admission, diagnostic, notes, facture_id, created_at, updated_at)
    VALUES (hospit_id, hosp_id, patient_id_v, medecin_id_v, chambre_id_v, lit_id_v, service_id_v,
            rec.statut::"StatutHospitalisation", date_v, date_sortie, rec.motif, rec.diagnostic, rec.notes, fact_id, date_v, date_v);

    -- Lignes hospitalisation : chambre (une par jour)
    FOR i IN 1..duree LOOP
      INSERT INTO lignes_hospitalisation (hospitalisation_id, type_ligne, statut, description, quantite, prix_unitaire, montant_total, prescrit_par, date_ligne, created_at)
      SELECT hospit_id, 'CHAMBRE', 'SERVI',
             'Chambre ' || rec.ch_num || ' — Jour ' || i,
             1, prix_journalier, prix_journalier,
             (SELECT prenom || ' ' || nom FROM utilisateurs WHERE id = admin_id),
             debut + ((rec.day_entree + i - 1) || ' days')::INTERVAL + INTERVAL '8 hours',
             date_v
      FROM chambres WHERE id = chambre_id_v;
    END LOOP;

    -- Lignes hospitalisation : médicaments
    INSERT INTO lignes_hospitalisation (hospitalisation_id, type_ligne, statut, description, quantite, prix_unitaire, montant_total, article_stock_id, prescrit_par, date_ligne, created_at)
    SELECT hospit_id, 'MEDICAMENT', 'SERVI',
           a.nom || ' x' || hm.qte,
           hm.qte, a.prix_unitaire, a.prix_unitaire * hm.qte, a.id,
           (SELECT prenom || ' ' || nom FROM utilisateurs WHERE id = medecin_id_v),
           date_v + INTERVAL '2 hours', date_v
    FROM _hmed hm
    JOIN articles_stock a ON a.code_article = hm.code AND a.hospital_id = hosp_id
    WHERE hm.ord = rec.ord;

    -- Lignes hospitalisation : actes
    INSERT INTO lignes_hospitalisation (hospitalisation_id, type_ligne, statut, description, quantite, prix_unitaire, montant_total, prescrit_par, date_ligne, created_at)
    SELECT hospit_id, 'ACTE_INFIRMIER', 'SERVI', description, qte, prix, prix * qte,
           (SELECT prenom || ' ' || nom FROM utilisateurs WHERE id = infirmier_id),
           date_v + INTERVAL '4 hours', date_v
    FROM _hacte WHERE ord = rec.ord;

    -- Mouvements stock : sortie pour chaque médicament
    FOR mrec IN
      SELECT a.id AS aid, a.quantite_stock AS before_qte, hm.qte AS qte_sortie, a.nom AS aname
      FROM _hmed hm
      JOIN articles_stock a ON a.code_article = hm.code AND a.hospital_id = hosp_id
      WHERE hm.ord = rec.ord
    LOOP
      INSERT INTO mouvements_stock (hospital_id, article_id, type_mouvement, quantite, quantite_avant, quantite_apres, motif, utilisateur_id, created_at)
      VALUES (hosp_id, mrec.aid, 'SORTIE', mrec.qte_sortie, mrec.before_qte,
              GREATEST(0, mrec.before_qte - mrec.qte_sortie),
              'Hospitalisation #' || rec.ord, pharmacien_id, date_v + INTERVAL '2 hours');

      UPDATE articles_stock
      SET quantite_stock = GREATEST(0, mrec.before_qte - mrec.qte_sortie)
      WHERE id = mrec.aid;
    END LOOP;

    -- Marquer chambre et lit indisponibles si EN_COURS
    IF rec.statut = 'EN_COURS' THEN
      UPDATE chambres SET est_disponible = FALSE WHERE id = chambre_id_v;
      IF lit_id_v IS NOT NULL THEN
        UPDATE lits SET est_disponible = FALSE WHERE id = lit_id_v;
      END IF;
    END IF;

    -- Écriture comptable si payée
    IF rec.fact_st = 'PAYEE' THEN
      INSERT INTO ecritures_comptables (hospital_id, utilisateur_id, type_ecriture, libelle, montant, date_ecriture, reference, facture_id, notes, created_at)
      VALUES (hosp_id, comptable_id, 'RECETTE',
              'Hospit. ' || num_facture, m_patient, date_sortie, num_facture, fact_id,
              'Séjour ' || duree || ' jour(s) — ' || rec.ch_num, date_sortie);
    END IF;
  END LOOP;

  DROP TABLE _hdef;
  DROP TABLE _hmed;
  DROP TABLE _hacte;

  -- ==========================================================
